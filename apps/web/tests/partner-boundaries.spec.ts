import {test,expect} from '@playwright/test';
import {localizedHref} from '../src/lib/i18n/routing';
import {partnerContextCopy} from '../src/lib/i18n/partner-context-copy';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('hoptrip.consent.v1',JSON.stringify({version:1,analytics:false,marketing:false,at:Date.now()})));});
for(const locale of ['pl','en','ru','uk'] as const)test(`${locale}: supported stay context and unsupported ticket changes are explicit`,async({page})=>{
 await page.goto(localizedHref('/deals/stay-context-overnight',locale));
 const flight=page.locator('.page-heading .lead'),before=await flight.textContent(),stay=page.locator('#accommodation');
 await page.locator('#stay-checkin').fill('2030-05-31');await page.locator('#stay-checkout').fill('2030-06-02');
 await page.locator('#stay-adults').fill('51');await expect(stay.locator('a[rel*="sponsored"]')).toHaveCount(0);
 await page.locator('#stay-adults').fill('2');const link=stay.locator('a[rel*="sponsored"]');await expect(link).toHaveCount(1);
 const url=new URL((await link.getAttribute('href'))!);
 expect(url.searchParams.get('checkin')).toBe('2030-05-31');expect(url.searchParams.get('checkout')).toBe('2030-06-02');
 expect(url.searchParams.get('adults')).toBe('2');expect(url.searchParams.get('aid')).toBe('hoptrip');
 for(const key of ['children','rooms','return_arrival'])expect(url.searchParams.has(key)).toBe(false);
 await expect(link).toHaveAttribute('target','_blank');await expect(link).toHaveAttribute('rel','sponsored noopener noreferrer');
 await expect(flight).toHaveText(before!);
 await page.reload();await expect(page.locator('#stay-checkout')).toHaveValue('2030-06-02');
 await page.goto(localizedHref('/deals/browser-13',locale));
 await expect(page.locator('#trip-events .partner-context-limitation')).toHaveText(partnerContextCopy[locale]);
 await page.goto(localizedHref('/deals/browser-deal',locale));
 await expect(page.locator('.booking-card a.cta')).toHaveAttribute('rel','sponsored noopener noreferrer');
 const datesCopy={pl:'Sprawdź daty i cenę u partnera.',en:'Check dates and price with the partner.',ru:'Проверьте даты и цену у партнёра.',uk:'Перевірте дати й ціну в партнера.'};
 await expect(page.getByTestId('flight-search-limitation')).toContainText(datesCopy[locale]);
 await page.goto(localizedHref('/info/barcelona-3-days',locale));
 await expect(page.locator('#destination-activities .partner-context-limitation')).toHaveText(partnerContextCopy[locale]);
 await page.goto(localizedHref('/info/malaga-airport',locale));
 await expect(page.locator('aside .partner-context-limitation')).toHaveText(partnerContextCopy[locale]);
 await page.setViewportSize({width:320,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
