import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {airportContextCopy} from '../src/lib/airport-context';
import {flightRouteCopy} from '../src/lib/i18n/flight-route-copy';
import {localizedHref} from '../src/lib/i18n/routing';
const fixture='http://127.0.0.1:8100';
test.beforeEach(async({page,request})=>{
 expect((await request.post(`${fixture}/__test__/airport-context-fixtures?enabled=true`)).ok()).toBe(true);
 await page.addInitScript(()=>localStorage.setItem('hoptrip.consent.v1',JSON.stringify({version:1,analytics:false,marketing:false,at:Date.now()})));
});
test.afterEach(async({request})=>{await request.post(`${fixture}/__test__/airport-context-fixtures?enabled=false`);});
for(const locale of ['pl','en','ru','uk'] as const)test(`${locale}: airport warnings, source disclosure, stale/unknown and route warning do not duplicate`,async({page,request})=>{
 test.setTimeout(120000);
 const c=airportContextCopy[locale];
 await page.goto(localizedHref('/deals?origin=WRO&departure_from=2030-11-08&departure_to=2030-11-08&sort=price',locale));
 const card=(slug:string)=>page.locator('.deal-card').filter({has:page.locator(`a[href*="/deals/airport-context-fixture-${slug}"]`)});
 const remote=card('remote');
 await expect(remote).toHaveCount(1);
 await expect(remote.locator('.airport-context-notice')).toContainText(c.remote);
 await expect(remote.locator('.airport-context-notice')).toContainText('≈45 km');
 await expect(remote.locator('.airport-context-notice')).toContainText(c.late);
 await expect(remote.locator('.airport-context-notice')).toContainText(c.earlyReturn);
 await expect(remote.locator('.flight-route-warning')).toHaveCount(1);
 await expect(remote.locator('.flight-route-warning')).toHaveText(flightRouteCopy[locale].departure.replace('{back}','MXP').replace('{out}','BGY'));
 await expect(remote.locator('.airport-context-notice')).not.toContainText(flightRouteCopy[locale].departure.split(':')[0]);
 await expect(card('paris').locator('.airport-context-notice')).toContainText('≈80 km');
 await expect(card('near').locator('.airport-context-notice')).not.toContainText(c.remote);
 await expect(card('unknown').locator('.airport-context-notice')).toContainText(c.unknown);
 await expect(card('stale').locator('.airport-context-notice')).toContainText(c.stale);
 await expect(card('stale').locator('.airport-context-notice')).not.toContainText('45 km');
 await expect(card('estimated').locator('.airport-context-notice')).toContainText(c.estimated);
 await remote.locator('.trip-details > summary').focus();await page.keyboard.press('Enter');
 const details=remote.locator('.airport-context-details');
 await expect(details).toBeVisible();await expect(details).toContainText(c.policy);
 await expect(details).toContainText(c.reviewed);await expect(details).toContainText('2026-11-03');
 await expect(details.locator('a')).toHaveCount(1);
 await expect(details.locator('a')).toHaveAttribute('href','https://www.milanbergamoairport.it/en/airport-infrastructure/');
 expect((await new AxeBuilder({page}).include('.deal-grid').analyze()).violations).toEqual([]);
 await page.setViewportSize({width:320,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await remote.screenshot({path:test.info().outputPath(`${locale}-airport-320.png`)});
 await remote.locator('.deal-card-link').click();
 await expect(page.locator('.detail-summary .airport-context-notice')).toContainText(c.remote);
 await expect(page.locator('.detail-summary .flight-route-warning')).toHaveCount(1);
 await page.locator('.detail-summary .trip-details > summary').click();
 await expect(page.locator('.detail-summary .airport-context-details')).toContainText(c.basis);
 const response=await request.get(`${fixture}/api/v1/deals/airport-context-fixture-remote`);
 expect(response.ok()).toBe(true);
 expect((await response.json()).destination_time.usable_city_minutes).toBeNull();
});
